'''Passando agora para o looping for:

Criar um looping for é algo bem simples e pode ser associado a mesma ideia de 
como se cria um while, sendo assim:'''

for letra in 'Alguma coisa aleatória':
    print(letra)

''' A primeira linha desse for diz o seguinte: "para cada letra na frase 'Alguma
coisa aleatória, faça algo' '''

'''Esse laço for irá printar cada letra separada da frase específicada'''

amigos = ['Efsu', 'Bolinha', 'Japonês', 'Maninha', 'Gu']

for amigo in amigos:
    print(amigo)
    